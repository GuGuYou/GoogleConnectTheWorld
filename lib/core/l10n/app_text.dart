/// 便捷扩展：ref.tr('key') 自动读取当前语言
extension TrRef on WidgetRef {
  String tr(String key) => AppText.get(watch(localeProvider).languageCode, key);
}

extension TrReader on Ref {
  String tr(String key) => AppText.get(read(localeProvider).languageCode, key);
}
